using Android.Content;
using Android.Content.PM;
using Android.Net.Http;
using Android.OS;
using Android.Runtime;
using Android.Util;
using Android.Views;
using Android.Webkit;
using Java.Time;
using Microsoft.Maui.Handlers;
using Microsoft.Maui.Platform;
using System.Text;
using AWebView = Android.Webkit.WebView;

namespace HybridWebView
{
    public class AndroidHybridWebViewClient : MauiWebViewClient
    {
        private readonly WeakReference<HybridWebViewHandler> _handlerRef;
        private string? _url;

        public AndroidHybridWebViewClient(HybridWebViewHandler handler) : base(handler)
        {
            _handlerRef = new WeakReference<HybridWebViewHandler>(handler);
        }


        private bool TryGetAttachedHandler(out HybridWebViewHandler handler)
        {
            if (_handlerRef.TryGetTarget(out var targetHandler) &&
                HasAttachedPlatformView(targetHandler) &&
                targetHandler.VirtualView != null)
            {
                handler = targetHandler;
                return true;
            }

            handler = null!;
            return false;
        }

        private static bool HasAttachedPlatformView(HybridWebViewHandler handler)
        {
            try
            {
                return handler.PlatformView != null;
            }
            catch (InvalidOperationException ioe) when (ioe.Message?.Contains("PlatformView cannot be null", StringComparison.OrdinalIgnoreCase) == true)
            {
                return false;
            }
        }

        public override bool ShouldOverrideUrlLoading(AWebView? view, IWebResourceRequest? request)
        {
            _url = request?.Url?.ToString();
            System.Diagnostics.Debug.WriteLine($"HybridWebView ShouldOverrideUrlLoading :{request?.IsForMainFrame} {request?.IsRedirect} {request?.Url}");
            return base.ShouldOverrideUrlLoading(view, request);
        }

        public override bool ShouldOverrideUrlLoading(AWebView? view, string? url)
        {
            _url = url;
            System.Diagnostics.Debug.WriteLine($"HybridWebView ShouldOverrideUrlLoading :{url}");
            return base.ShouldOverrideUrlLoading(view, url);
        }

        public override void OnPageStarted(AWebView? view, string? url, Android.Graphics.Bitmap? favicon)
        {
            if (url == "about:blank")
                return;

            if (!TryGetAttachedHandler(out var handler)) return;           // <— guard

            // Skip the synthetic initial callback generated by reattaching the existing WebView after process/Activity recreation
            if (BeginSkipIfRestoring(handler))
            {
                System.Diagnostics.Debug.WriteLine("HybridWebView OnPageStarted skipped (restoring state)");
                return;
            }

            System.Diagnostics.Debug.WriteLine($"HybridWebView OnPageStarted :{url}");
            base.OnPageStarted(view, url, favicon);
            _url = null;
        }
        public override void OnPageFinished(AWebView? view, string? url)
        {
            if (url == "about:blank")
                return;

            if (!TryGetAttachedHandler(out var handler)) return;           // <— guard

            // If we were in a restore cycle skip this synthetic finish and mark restore complete
            if (EndSkipIfRestoring(handler))
            {
                System.Diagnostics.Debug.WriteLine("HybridWebView OnPageFinished skipped & restore completed");
                return;
            }

            base.OnPageFinished(view, url);
        }

        // Some Android/WebView versions can invoke OnReceivedError after the handler has been disconnected/restored.
        // MAUI's base implementation accesses Handler.PlatformView which throws if null. Guard and swallow in that case.
        public override void OnReceivedError(AWebView? view, IWebResourceRequest? request, WebResourceError? error)
        {
            if (!TryGetAttachedHandler(out var handler)) return;           // <— guard
            
            try
            {
                base.OnReceivedError(view, request, error);
            }
            catch (InvalidOperationException ioe) when (ioe.Message?.Contains("PlatformView cannot be null", StringComparison.OrdinalIgnoreCase) == true)
            {
                Android.Util.Log.Warn("HybridWebView", $"OnReceivedError skipped due to disposed PlatformView. error={error?.ErrorCode} desc={error?.Description}");
            }
        }

        public override void OnReceivedError(AWebView? view, ClientError errorCode, string? description, string? failingUrl)
        {
            if (!TryGetAttachedHandler(out var handler)) return;           // <— guard
            
            try
            {
                base.OnReceivedError(view, errorCode, description, failingUrl);
            }
            catch (InvalidOperationException ioe) when (ioe.Message?.Contains("PlatformView cannot be null", StringComparison.OrdinalIgnoreCase) == true)
            {
                Android.Util.Log.Warn("HybridWebView", $"OnReceivedError (legacy) skipped due to disposed PlatformView. error={errorCode} desc={description} url={failingUrl}");
            }
        }


        public override WebResourceResponse? ShouldInterceptRequest(AWebView? view, IWebResourceRequest? request)
        {
            var fullUrl = request?.Url?.ToString();
            if (fullUrl == null || request == null || !request.IsForMainFrame)
                return base.ShouldInterceptRequest(view, request);

            if (!TryGetAttachedHandler(out var handler))
                return base.ShouldInterceptRequest(view, request);

            var requestUri = QueryStringHelper.RemovePossibleQueryString(fullUrl);

            System.Diagnostics.Debug.WriteLine($"HybridWebView ShouldInterceptRequest :{request.IsForMainFrame} {request.IsRedirect} {fullUrl}");

            try
            {
                var webView = (HybridWebView)handler.VirtualView;
                var cookieManager = Android.Webkit.CookieManager.Instance;

                if (cookieManager == null || webView == null)
                    return base.ShouldInterceptRequest(view, request);

                foreach (var item in HybridWebView.AllRequestsCookies)
                {
                    var val = $"{item.Key}={item.Value}";
                    cookieManager.SetCookie("/", val);
                }

                return base.ShouldInterceptRequest(view, request);
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine("HybridWebView Error getting cookie manager or webview. " + ex.ToString());
                return base.ShouldInterceptRequest(view, request);
            }
        }

        private protected static IDictionary<string, string> GetHeaders(string contentType) =>
            new Dictionary<string, string> {
                { "Content-Type", contentType },
            };

        bool _skipNext;
        bool BeginSkipIfRestoring(HybridWebViewHandler h)
        {
            if (h.IsRestoringState && !_skipNext) { _skipNext = true; return true; }
            return false;
        }
        bool EndSkipIfRestoring(HybridWebViewHandler h)
        {
            if (_skipNext) { _skipNext = false; h.FinishRestore(); return true; }
            return false;
        }


    }

